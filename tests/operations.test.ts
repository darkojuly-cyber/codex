it('uses guild nicknames and individual app overrides in the live Discord adapter', async () => {
  const { DiscordTransport } = await import('../packages/core/src/transport.js');
  const staffRole = '823456789012345678';
  const env = { ...readEnv(), APP_MODE: 'discord' as const, DISCORD_TOKEN: 'test', DISCORD_WRITES_ENABLED: 'true' as const, DISCORD_GUILD_ID: channel, SUPER_ADMIN_USER_IDS: root.id, STAFF_ROLE_IDS: staffRole };
  const adapter = new DiscordTransport(env, db);
  vi.spyOn(adapter.rest, 'get').mockResolvedValue({ roles: [staffRole], nick: '服务器昵称', user: { username: 'operator', global_name: '全局昵称' } });
  expect(await adapter.memberProfile(mod.id)).toEqual({ displayName: '服务器昵称', username: 'operator' });
  await ops.authorize(root, mod.id, { role: 'SUPPORT', revoked: false, expectedVersion: 0, reason: 'Support-only console duties' }, [root.id]);
  expect((await adapter.ticketStaff(mod.id)).role).toBe('SUPPORT');
  const patch = vi.spyOn(adapter.rest, 'patch').mockResolvedValue({});
  vi.mocked(adapter.rest.get).mockImplementation(async () => ({ id: manager.id, guild_id: channel, type: ChannelType.GuildText }));
  await adapter.syncTicket('923456789012345678', null, { creator_id: support.id, assigned_to: null, status: 'OPEN' });
  const overwrites = (patch.mock.calls[0][1] as { body: { permission_overwrites: { id: string; allow: string; deny: string }[] } }).body.permission_overwrites;
  expect(overwrites.find(row => row.id === mod.id)).toMatchObject({ allow: '0', deny: '1024' });
  await ops.authorize(root, mod.id, { role: 'SUPPORT', revoked: true, expectedVersion: 1, reason: 'Revoke support permissions' }, [root.id]);
  vi.mocked(adapter.rest.get).mockResolvedValue({ roles: [staffRole], user: { username: 'operator' } });
  await expect(adapter.ticketStaff(mod.id)).rejects.toMatchObject({ code: 'STAFF_ACCESS_REVOKED' });
  vi.restoreAllMocks();
});
