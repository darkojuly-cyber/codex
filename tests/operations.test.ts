it('deduplicates observed events, counts unique speakers across days and applies calendar boundaries', async () => {
  await ops.heartbeat(true, true, false);
  await ops.membership('JOIN', manager.id, 'one-join'); await ops.membership('JOIN', manager.id, 'one-join');
  await ops.membership('LEAVE', support.id, 'one-leave'); await ops.membership('LEAVE', support.id, 'duplicate-leave-delivery');
  const message = { id: '623456789012345678', user: manager.id, channel, category: null, parent: null, at: new Date() };
  await ops.message(message); await ops.message(message);
  await ops.message({ ...message, id: '623456789012345679', at: new Date(Date.now() - 86400000) });
  await ops.message({ ...message, id: '623456789012345680', user: mod.id });
  const week = await ops.overview(mod, 7, 'Asia/Shanghai');
  expect(week.totals).toEqual({ joins: 1, leaves: 1, messages: 3, speakers: 2 });
  expect(week.daily.reduce((sum, row) => sum + Number(row.speakers), 0)).toBe(3);
  expect((await ops.overview(mod, 1, 'Asia/Shanghai')).totals.messages).toBe(2);
  await expect(ops.overview(support, 7, 'UTC')).rejects.toMatchObject({ code: 'FORBIDDEN' });
});
it('keeps nickname and ID distinct and falls back to the last observed nickname on provider failure', async () => {
  await ops.observeProfile(manager.id, '社区运营昵称', 'operator');
  expect(await ops.profile(manager.id)).toMatchObject({ user_id: manager.id, display_name: '社区运营昵称', username: 'operator' });
  await db.query("UPDATE member_profile SET updated_at=now()-interval '1 hour'");
  const transport = new MockTransport(); Object.assign(transport, { memberProfile: vi.fn().mockRejectedValue(new Error('unavailable')) });
  expect((await new Operations(db, transport, false).profile(manager.id)).display_name).toBe('社区运营昵称');
  expect((await ops.profile('999999999999999999')).display_name).toBeNull();
});
it('allows only super-admin grants, invalidates sessions, protects roots and enforces version checks', async () => {
  const input = { role: 'MODERATOR', revoked: false, expectedVersion: 0, reason: 'Authorize a trusted moderator' };
  await expect(ops.authorize(manager, mod.id, input, [root.id])).rejects.toMatchObject({ code: 'FORBIDDEN' });
  await expect(ops.authorize(root, root.id, input, [root.id])).rejects.toMatchObject({ code: 'ROOT_ACCESS_PROTECTED' });
  await db.query("INSERT INTO admin_session(token_hash,user_id,role,csrf,expires_at) VALUES('token',$1,'SUPPORT','csrf',now()+interval '1 day')", [mod.id]);
  await ops.authorize(root, mod.id, input, [root.id]);
  expect(await db.query('SELECT * FROM admin_session')).toHaveLength(0);
  const env = { ...readEnv(), SUPER_ADMIN_USER_IDS: root.id };
  expect(await effectiveStaff(db, env, mod.id, [])).toEqual(mod);
  await expect(ops.authorize(root, mod.id, input, [root.id])).rejects.toMatchObject({ code: 'CONFIG_CHANGED_RELOAD' });
  await ops.authorize(root, mod.id, { ...input, revoked: true, expectedVersion: 1 }, [root.id]);
  await expect(effectiveStaff(db, env, mod.id, [])).rejects.toMatchObject({ code: 'STAFF_ACCESS_REVOKED' });
  expect(await effectiveStaff(db, env, root.id, [])).toEqual(root);
});
it('requires explicit keyword scope, stores matches without bodies and requires human review', async () => {
  const config = { enabled: true, channelIds: [channel], excludedCategoryIds: [], keywords: ['scam', '诈骗'] };
  await expect(ops.saveSettings(manager, { body: config, expectedVersion: 1 })).rejects.toMatchObject({ code: 'FORBIDDEN' });
  await expect(ops.saveSettings(root, { body: { ...config, channelIds: [] }, expectedVersion: 1 })).rejects.toMatchObject({ code: 'RISK_SCOPE_REQUIRED' });
  await ops.saveSettings(root, { body: config, expectedVersion: 1 });
  const message = { id: '623456789012345678', user: manager.id, channel, category: null, parent: null, at: new Date(), content: 'This is a SCAM; private text must not be stored.' };
  await ops.message(message); await ops.message(message);
  await ops.message({ ...message, id: '623456789012345679', channel: '723456789012345678' });
  const signals = await ops.risks(mod);
  expect(signals.total).toBe(1); expect(signals.entries[0].matches).toEqual(['scam']);
  expect(JSON.stringify(signals)).not.toContain('private text');
  await expect(ops.review(support, message.id, { status: 'CONFIRMED', note: 'Needs follow-up' })).rejects.toMatchObject({ code: 'FORBIDDEN' });
  await ops.review(mod, message.id, { status: 'DISMISSED', note: 'Discussing scam prevention' });
  await expect(ops.review(mod, message.id, { status: 'CONFIRMED', note: 'Changed review' })).rejects.toMatchObject({ code: 'RISK_ALREADY_REVIEWED' });
  expect((await ops.overview(mod, 7, 'UTC')).riskOpen).toBe(0);
});
it('rejects private, staff-only, bot, webhook and cross-guild message collection before reading content', async () => {
  const recorder = { observeProfile: vi.fn(), message: vi.fn() } as unknown as Operations;
  const make = (publicView: boolean, type = ChannelType.GuildText) => ({ guildId: channel, guild: { roles: { everyone: {} } }, channelId: channel, channel: { type, parentId: null, isThread: () => false, permissionsFor: () => ({ has: () => publicView }) }, author: { id: manager.id, bot: false, username: 'operator' }, createdAt: new Date(), id: manager.id, content: 'scam' }) as unknown as Message;
  await observePublicMessage(make(false), recorder, channel, true);
  await observePublicMessage(make(true, ChannelType.PrivateThread), recorder, channel, true);
  await observePublicMessage(make(true), recorder, '999999999999999999', true);
  const bot = make(true); Object.assign(bot.author, { bot: true }); await observePublicMessage(bot, recorder, channel, true);
  expect(recorder.message).not.toHaveBeenCalled();
  await observePublicMessage(make(true), recorder, channel, false);
  expect(recorder.message).toHaveBeenCalledWith(expect.objectContaining({ content: undefined }));
});
