import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('staff can create a prompt, handle a private mock ticket, publish configuration and send a confirmed message', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Enter as SUPER ADMIN' }).click();
  await expect(page.getByRole('heading', { name: 'Your community, at a glance.' })).toBeVisible();
  await expect(page.getByText('MOCK ENVIRONMENT')).toBeVisible();
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Mimo & Ideas' }).click();
  await page.getByRole('button', { name: '✳ Surprise me!' }).click();
  await page.getByRole('button', { name: 'Generate game prompt' }).click();
  await expect(page.getByText('Core gameplay:', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Create mock ticket' }).click();
  await expect(page.getByRole('status')).toContainText('Created private mock ticket');
  await page.getByRole('button', { name: 'Tickets' }).click();
  await page.getByRole('button', { name: '#1', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Ticket #1/ })).toBeVisible();
  await page.getByLabel('Reason / internal note').fill('Reviewed in local browser acceptance.');
  await page.getByRole('button', { name: 'Save status & note' }).click();
  await expect(page.getByRole('status')).toContainText('Ticket updated');
  await page.getByRole('button', { name: 'Settings' }).click();
  await page.getByLabel('Approved publishing channel IDs').fill('123456789012345678');
  await page.getByRole('button', { name: 'Save configuration draft' }).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.getByRole('button', { name: 'Lifecycle' }).click();
  page.on('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('published');
  await page.getByLabel('messaging', { exact: true }).check();
  await page.getByRole('button', { name: 'Validate & save draft' }).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('published');
  await page.getByRole('button', { name: 'Messaging' }).click();
  await page.getByLabel('Channel ID', { exact: true }).fill('123456789012345678');
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('<img src=x onerror="window.__evomemeXssProbe=1">');
  await expect(page.locator('.message-preview img')).toHaveCount(0);
  expect(await page.evaluate(() => '__evomemeXssProbe' in window)).toBe(false);
  const deliveryText = `A local acceptance message. @everyone remains suppressed. ${randomUUID()}`;
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill(deliveryText);
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Message saved');
  const confirmation = page.waitForResponse(response => response.url().endsWith('/confirm') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Confirm delivery' }).click();
  const confirmed = await confirmation;
  expect(confirmed.ok()).toBe(true);
  const queued = await confirmed.json();
  expect(queued.status).toBe('SCHEDULED');
  // The embedded mock worker ticks every 2s. Wait for this exact job rather than
  // refreshing and immediately counting a DOM list that is cleared while loading.
  await expect.poll(async () => {
    const response = await page.request.get('/api/messages');
    expect(response.ok()).toBe(true);
    const jobs = await response.json() as { id: string; status: string; error_code: string | null }[];
    const job = jobs.find(job => job.id === queued.id);
    return `${job?.status ?? 'MISSING'}:${job?.error_code ?? ''}`;
  }, { timeout: 15000, intervals: [500, 1000], message: 'Confirmed mock message should be sent by the embedded worker' }).toBe('SENT:');
  await page.getByRole('button', { name: '↻ Refresh' }).click();
  await expect(page.locator('.job').filter({ hasText: deliveryText }).getByText('SENT', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/message-delivery.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Overview' }).click();
  await expect(page.getByRole('heading', { name: 'Your community, at a glance.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('Support sees a restricted console with server-enforced access', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Enter as SUPPORT', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your community, at a glance.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Lifecycle' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Messaging' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Tickets' }).click();
  await expect(page.getByText('No tickets yet.', { exact: false })).toBeVisible();
  const status = await page.evaluate(async () => (await fetch('/api/config')).status);
  expect(status).toBe(403);
});
